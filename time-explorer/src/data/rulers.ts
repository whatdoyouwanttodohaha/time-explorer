import type { Period, RulerLane } from '../types';
import { MAX_YEAR } from './tracks';

/**
 * 나라별 지도자 재위 막대. 줄(트랙) id → lane 목록.
 * 한 lane 안의 재위는 겹치지 않게 시간순으로 쓴다. 재위는 [시작, 끝) 구간이다.
 * 튜플: [이름, 시작, 끝, 설명?]. 끝이 NOW면 현재 재임 중이다.
 */
type R = [name: string, start: number, end: number, note?: string];

const NOW = MAX_YEAR;

function lane(trackId: string, id: string, name: string, rows: R[]): RulerLane {
  return {
    id: `${trackId}-${id}`,
    name,
    rulers: rows.map(([n, start, end, note], i): Period => ({
      id: `${trackId}-${id}-${i}`,
      name: n,
      start,
      end: Math.max(end, start + 1),
      ...(note ? { note } : {}),
    })),
  };
}

